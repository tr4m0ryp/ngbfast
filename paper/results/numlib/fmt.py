"""LaTeX macro collection and number formatting (every macro carries a source comment)."""

import re


def f(x, nd=3, sign=False):
    s = f"{x:+.{nd}f}" if sign else f"{x:.{nd}f}"
    return s.replace("-", "$-$") if s.startswith("-") else s


def fint(x):
    return f"{int(round(x)):,}".replace(",", "{,}")


def fx(x):
    """A speed ratio: two decimals below 10, none above, thousands grouped."""
    if x < 10:
        return f"{x:.2f}"
    return fint(x)


class Macros:
    def __init__(self):
        self.lines = ["% Generated by results/make_numbers.py. Do not edit by hand."]
        self.names = set()

    def section(self, title):
        self.lines += ["", f"% ---- {title}"]

    def add(self, name, value, src):
        if not re.fullmatch(r"[A-Za-z]+", name):
            raise ValueError(f"macro name must be letters only: {name}")
        if name in self.names:
            raise ValueError(f"duplicate macro {name}")
        self.names.add(name)
        self.lines.append(f"% {src}")
        self.lines.append(f"\\newcommand{{\\{name}}}{{{value}}}")

    def text(self):
        return "\n".join(self.lines) + "\n"
